 assert.equal(parseCampaignReference('customer-private-id'),null);
 assert.equal(parseCampaignReference('da1_%%%'),null);
 const max=captureCampaign('?utm_source=instagram&utm_campaign='+ 'a'.repeat(99)+'&utm_content='+'b'.repeat(99),null);
 assert.ok(campaignReference(max).length<=200);
 const href='https://buy.stripe.com/28EcN699l8oQ9aC5Ao6kg02?prefilled_promo_code=CREATOR';
 const decorated=attributeCheckout(href,tag);const url=new URL(decorated);
 assert.equal(url.searchParams.get('client_reference_id'),ref);
 assert.equal(url.searchParams.get('prefilled_promo_code'),'CREATOR');
 assert.equal(attributeCheckout(decorated,{...tag,source:'youtube'}),decorated,'Existing attribution is not overwritten');
 assert.equal(attributeCheckout(href+'&client_reference_id=affiliate-id',tag),href+'&client_reference_id=affiliate-id');
 assert.equal(attributeCheckout('https://evil.example/pay',tag),'https://evil.example/pay');
 assert.equal(attributeCheckout('https://buy.stripe.com/unrecognized',tag),'https://buy.stripe.com/unrecognized');
 assert.equal(attributeCheckout(href,null),href);
 const row={id:'cs1',livemode:true,created:100,status:'complete',payment_status:'paid',amount_total:1499,currency:'usd',client_reference_id:ref,mode:'subscription'};
 const rows=[row,row,{...row,id:'trial',amount_total:0,payment_status:'no_payment_required',subscription:{trial_start:102}},{...row,id:'free',amount_total:0,payment_status:'no_payment_required'}, {...row,id:'unpaid',payment_status:'unpaid'}, {...row,id:'open',status:'open'}, {...row,id:'untagged',client_reference_id:null},{...row,id:'eur',currency:'eur',amount_total:1800}];
