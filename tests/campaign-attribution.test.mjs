 assert.equal(summary.scannedSessions,7);assert.equal(summary.taggedSessions,6);assert.equal(summary.untaggedSessions,1);
 const usd=summary.groups.find(g=>g.currency==='usd');
 assert.equal(usd.paidCheckouts,1);assert.equal(usd.initialAmountTotal,1499);assert.equal(usd.trialStarts,1);assert.equal(usd.noInitialPayment,2);
 assert.equal(summary.groups.find(g=>g.currency==='eur').initialAmountTotal,1800);
 assert.throws(()=>summarizeConversions([{...row,livemode:false}],90,200),/TEST_CHECKOUT/);
 assert.equal(summarizeConversions([row],200,300).scannedSessions,0);
 console.log('PASS: same-tab campaign carryover/expiry, bounded references, checkout destination and affiliate preservation, deduplicated live sessions, unpaid/free/trial separation, missing attribution and currency-separated totals.');
